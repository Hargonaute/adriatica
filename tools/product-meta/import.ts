import { config as loadEnv } from 'dotenv';
loadEnv({ path: '.env.local' });
loadEnv({ path: '.env' });

/**
 * Import product filter metadata (Famille / Problématique / Cultures) from the
 * catalogue into `pages.meta.product` of existing `produit-…` pages.
 *
 * Usage:
 *   npx tsx tools/product-meta/import.ts                 # dry run (default, read-only)
 *   npx tsx tools/product-meta/import.ts --apply         # write
 *   npx tsx tools/product-meta/import.ts --apply --overwrite
 *
 * Options:
 *   --file <path>       catalogue JSON (default tools/product-meta/catalogue.json,
 *                       generated by xlsx-to-json.py)
 *   --overrides <path>  JSON map { "Produit name": "produit-page-slug" | [slugs…] }
 *                       for products whose page slug differs from slugify(name);
 *                       an array applies one row to several pages (Gamme variants)
 *                       (default tools/product-meta/slug-overrides.json)
 *   --overwrite         also replace pages that already have meta.product
 *
 * Safety:
 *   - Only the `product` key inside `meta` is written (jsonb_set); blocks, SEO
 *     fields, status and slugs are never touched. No page is created or deleted.
 *   - Writes run in one transaction; a JSON backup of every touched page's
 *     previous `meta` is written to tools/product-meta/backups/ first.
 *   - Tip: make sure nobody has those product pages open in the editor while
 *     applying — saving an editor tab opened before the import would write
 *     back the old meta.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { planImport, type CatalogueRow, type ExistingPage } from '../../src/lib/products/importPlan';

function argValue(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function describeTarget(url: string): string {
  try {
    const u = new URL(url);
    return `${u.hostname}${u.pathname}`;
  } catch {
    return '(unparseable DATABASE_URL)';
  }
}

async function main() {
  const apply = process.argv.includes('--apply');
  const overwrite = process.argv.includes('--overwrite');
  const dir = join(process.cwd(), 'tools', 'product-meta');
  const file = argValue('--file') ?? join(dir, 'catalogue.json');
  const overridesFile = argValue('--overrides') ?? join(dir, 'slug-overrides.json');

  const rows = JSON.parse(readFileSync(file, 'utf8')) as CatalogueRow[];
  const slugOverrides = existsSync(overridesFile)
    ? (JSON.parse(readFileSync(overridesFile, 'utf8')) as Record<string, string | string[]>)
    : {};

  const connectionString = process.env.DATABASE_URL ?? process.env.POSTGRES_URL;
  if (!connectionString) throw new Error('DATABASE_URL is not set');

  console.log(`Mode:     ${apply ? 'APPLY (writes)' : 'dry run (read-only)'}${overwrite ? ' + overwrite' : ''}`);
  console.log(`Database: ${describeTarget(connectionString)}`);
  console.log(`Rows:     ${rows.length} from ${file}\n`);

  const { pool } = await import('../../src/lib/db/pool');
  const client = await pool.connect();
  try {
    const { rows: pages } = await client.query<ExistingPage>(
      `SELECT id, slug, title, status, meta FROM pages
       WHERE slug LIKE 'produit-%' AND is_template = false ORDER BY slug`
    );

    const plan = planImport(rows, pages, { overwrite, slugOverrides });

    console.log(`Product pages found: ${pages.length}`);
    console.log(`Will update:         ${plan.updates.length}`);
    plan.updates.forEach((u) =>
      console.log(
        `  ✓ ${u.slug}  [${u.product.famille ?? '—'}] [${(u.product.problematiques ?? []).join(' | ') || '—'}] [${(u.product.cultures ?? []).join(', ') || '—'}]`
      )
    );
    if (plan.inheritedCultures.length) {
      console.log(`\nCultures inherited from the main product: ${plan.inheritedCultures.length}`);
      plan.inheritedCultures.forEach((i) => console.log(`  ↳ ${i.produit} ← ${i.from}`));
    }
    if (plan.skippedExisting.length) {
      console.log(`\nSkipped (already tagged, use --overwrite): ${plan.skippedExisting.length}`);
      plan.skippedExisting.forEach((s) => console.log(`  • ${s.slug}`));
    }
    if (plan.duplicates.length) {
      console.log(`\nSkipped (several rows → same page): ${plan.duplicates.length}`);
      plan.duplicates.forEach((d) => console.log(`  ! ${d.slug} ← ${d.produits.join(', ')}`));
    }
    if (plan.noPage.length) {
      console.log(`\nRows without a product page (not created): ${plan.noPage.length}`);
      plan.noPage.forEach((n) =>
        console.log(
          `  - ${n.produit} (${n.type}) → expected ${n.expectedSlug}` +
            (n.suggestions.length ? `   maybe: ${n.suggestions.join(', ')}` : '')
        )
      );
    }
    if (plan.pagesWithoutRow.length) {
      console.log(`\nProduct pages with no catalogue row (untouched): ${plan.pagesWithoutRow.length}`);
      plan.pagesWithoutRow.forEach((s) => console.log(`  - ${s}`));
    }
    if (plan.warnings.length) {
      console.log(`\nData warnings (still applied): ${plan.warnings.length}`);
      plan.warnings.forEach((w) => console.log(`  ⚠ ${w.produit}: ${w.message}`));
    }

    if (!apply) {
      console.log('\nDry run — nothing written. Re-run with --apply to write.');
      return;
    }
    if (plan.updates.length === 0) {
      console.log('\nNothing to apply.');
      return;
    }

    const ids = plan.updates.map((u) => u.pageId);
    const backup = pages.filter((p) => ids.includes(p.id)).map((p) => ({ id: p.id, slug: p.slug, meta: p.meta }));
    const backupDir = join(dir, 'backups');
    mkdirSync(backupDir, { recursive: true });
    const backupFile = join(backupDir, `meta-backup-${new Date().toISOString().replace(/[:.]/g, '-')}.json`);
    writeFileSync(backupFile, JSON.stringify(backup, null, 2));
    console.log(`\nBackup of previous meta: ${backupFile}`);

    await client.query('BEGIN');
    try {
      for (const u of plan.updates) {
        const res = await client.query(
          `UPDATE pages
             SET meta = jsonb_set(COALESCE(meta, '{}'::jsonb), '{product}', $1::jsonb, true)
           WHERE id = $2 AND slug = $3`,
          [JSON.stringify(u.product), u.pageId, u.slug]
        );
        if (res.rowCount !== 1) throw new Error(`Expected 1 row for ${u.slug}, got ${res.rowCount}`);
      }
      await client.query('COMMIT');
      console.log(`Applied ${plan.updates.length} updates.`);
    } catch (e) {
      await client.query('ROLLBACK');
      console.error('Rolled back — nothing written.');
      throw e;
    }
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
